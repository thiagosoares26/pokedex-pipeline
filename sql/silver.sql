CREATE SCHEMA IF NOT EXISTS silver;

CREATE TABLE IF NOT EXISTS silver.dim_geracao (
    sk_geracao      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_geracao  SMALLINT NOT NULL UNIQUE,
    nome_geracao    TEXT     NOT NULL,
    regiao          TEXT     NOT NULL
);

CREATE TABLE IF NOT EXISTS silver.dim_tipo (
    sk_tipo             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_tipo_pokeapi     SMALLINT UNIQUE,
    nome_tipo           TEXT    NOT NULL UNIQUE,
    nome_tipo_pt        TEXT    NOT NULL UNIQUE,
    eh_membro_especial  BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS silver.dim_pokemon (
    sk_pokemon          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero_csv          INTEGER      NOT NULL UNIQUE,
    numero_pokedex      INTEGER,
    id_pokeapi          INTEGER,
    nome                TEXT         NOT NULL,
    nome_pokeapi        TEXT         NOT NULL,
    especie             TEXT         NOT NULL,
    categoria_forma     TEXT         NOT NULL,
    status_conciliacao  TEXT         NOT NULL,
    tipo_primario       TEXT         NOT NULL,
    tipo_secundario     TEXT         NOT NULL,
    numero_geracao      SMALLINT     NOT NULL,
    geracao             TEXT         NOT NULL,
    regiao              TEXT         NOT NULL,
    categoria_raridade  TEXT         NOT NULL,
    lendario_csv        BOOLEAN      NOT NULL,
    habitat             TEXT         NOT NULL,
    cor                 TEXT         NOT NULL,
    forma_corporal      TEXT         NOT NULL,
    taxa_crescimento    TEXT         NOT NULL,
    grupos_ovo          TEXT         NOT NULL,
    taxa_captura        SMALLINT,
    felicidade_base     SMALLINT,
    experiencia_base    SMALLINT,
    altura_m            NUMERIC(5,1),
    peso_kg             NUMERIC(6,1),
    qtd_habilidades     SMALLINT,
    hp                  SMALLINT     NOT NULL,
    ataque              SMALLINT     NOT NULL,
    defesa              SMALLINT     NOT NULL,
    ataque_especial     SMALLINT     NOT NULL,
    defesa_especial     SMALLINT     NOT NULL,
    velocidade          SMALLINT     NOT NULL,
    total_status        SMALLINT     NOT NULL,
    eh_membro_especial  BOOLEAN      NOT NULL,
    CONSTRAINT ck_dim_pokemon_categoria_raridade
        CHECK (categoria_raridade IN ('Comum', 'Bebê', 'Lendário', 'Mítico', 'Não informado')),
    CONSTRAINT ck_dim_pokemon_categoria_forma
        CHECK (categoria_forma IN ('Padrão', 'Mega', 'Primal', 'Outra forma', 'Não informado'))
);

CREATE TABLE IF NOT EXISTS silver.efetividade_tipo (
    sk_tipo_atacante  INTEGER      NOT NULL REFERENCES silver.dim_tipo (sk_tipo),
    sk_tipo_defensor  INTEGER      NOT NULL REFERENCES silver.dim_tipo (sk_tipo),
    multiplicador     NUMERIC(3,2) NOT NULL CHECK (multiplicador IN (0, 0.5, 1, 2)),
    PRIMARY KEY (sk_tipo_atacante, sk_tipo_defensor)
);

CREATE TABLE IF NOT EXISTS silver.fato_confronto (
    id_combate                   INTEGER  NOT NULL,
    atacou_primeiro              SMALLINT NOT NULL CHECK (atacou_primeiro IN (0, 1)),
    sk_pokemon                   INTEGER  NOT NULL REFERENCES silver.dim_pokemon (sk_pokemon),
    sk_oponente                  INTEGER  NOT NULL REFERENCES silver.dim_pokemon (sk_pokemon),
    sk_tipo_primario             INTEGER  NOT NULL REFERENCES silver.dim_tipo (sk_tipo),
    sk_tipo_secundario           INTEGER  NOT NULL REFERENCES silver.dim_tipo (sk_tipo),
    sk_tipo_oponente_primario    INTEGER  NOT NULL REFERENCES silver.dim_tipo (sk_tipo),
    sk_tipo_oponente_secundario  INTEGER  NOT NULL REFERENCES silver.dim_tipo (sk_tipo),
    sk_geracao                   INTEGER  NOT NULL REFERENCES silver.dim_geracao (sk_geracao),
    sk_geracao_oponente          INTEGER  NOT NULL REFERENCES silver.dim_geracao (sk_geracao),
    venceu                       SMALLINT NOT NULL CHECK (venceu IN (0, 1)),
    diferenca_velocidade         SMALLINT NOT NULL,
    diferenca_total_status       SMALLINT NOT NULL,
    PRIMARY KEY (id_combate, atacou_primeiro)
);

CREATE INDEX IF NOT EXISTS ix_fato_confronto_pokemon ON silver.fato_confronto (sk_pokemon);
CREATE INDEX IF NOT EXISTS ix_fato_confronto_oponente ON silver.fato_confronto (sk_oponente);
CREATE INDEX IF NOT EXISTS ix_fato_confronto_tipos ON silver.fato_confronto (sk_tipo_primario, sk_tipo_oponente_primario);
